"""Assemble results/RESULTS.md from the generated result files (numbers are never typed by hand)."""
from _common import RESULTS, load_json


def pct(x):
    return f"{100 * x:.0f}%"


def main() -> None:
    v = load_json("verification.json")
    sc = load_json("scaling.json")
    ex = load_json("experiments_summary.json")
    e1, e2 = ex["exp1"], ex["exp2"]
    cc = load_json("crosscheck.json")
    bm = load_json("benchmark.json")
    P = v["policies"]
    ref = v["maximally_permissive_reference"]
    L = []
    add = L.append

    add("# Results (auto-generated by `scripts/make_report.py`)\n")
    add("Everything below is produced by the code in this repository; re-run `make reproduce` to regenerate it.\n")

    add("## 1. Exhaustive verification (untimed, batch 2A + 2B)\n")
    add("| Policy | Reachable markings | Deadlocks with unfinished jobs | Markings that can no longer complete the batch | Invariants hold on all markings | Markings with both machines processing | Max parts in cell |")
    add("|---|---:|---:|---:|:---:|---:|---:|")
    names = {"unrestricted": "Unrestricted dispatch", "one_active": "One active part", "supervisor": "Control-place supervisor"}
    for pol, d in P.items():
        add(f"| {names[pol]} | {d['reachable_markings']} | {d['deadlocks_with_unfinished_jobs']} | {d['markings_that_cannot_complete']} | "
            f"{'yes' if d['invariants_hold_on_all_markings'] else '**NO**'} | {d['markings_with_both_machines_processing']} | {d['max_parts_in_cell']} |")
    u = P["unrestricted"]
    add(f"\n**Shortest deadlock trace (unrestricted):** `{' → '.join(u['shortest_deadlock_trace'])}`\n")
    add(f"Only {u['deadlocks_with_unfinished_jobs']} markings are terminal deadlocks, but {u['markings_that_cannot_complete']} reachable markings "
        f"can no longer complete the batch ({v['unrestricted_doomed_but_not_yet_deadlocked']} of them are 'doomed but not yet deadlocked'): "
        "the point of no return comes *before* the machines visibly stop, so a monitor that only waits for a stall reacts too late.\n")
    add("**P-invariants of the supervised net** (each holds on every reachable marking):\n")
    for inv in P["supervisor"]["p_invariants"]:
        add(f"- `{inv}`")
    add("\nThe first two are the machine-conservation laws (a machine is free or held by exactly one part, whether processing or finished). "
        "The `CTRL` invariant is the interlock: at most one part occupies a *first-stage* position (processing or finished, waiting to transfer) at any time.\n")

    add("## 2. How permissive is the control place?\n")
    add("Reference = the *maximally permissive* safe behaviour: the largest set of plant markings that is closed under the "
        "uncontrollable machine events and from which the batch can always still be completed (computed as a fixpoint on the unrestricted plant). "
        "No deadlock-free, nonblocking supervisor can allow more than this.\n")
    add(f"| | Reachable markings | Safe markings given up | Safe transitions given up | Equals maximally permissive |")
    add("|---|---:|---:|---:|:---:|")
    add(f"| Maximally permissive reference | {ref['reachable_markings']} | – | – | – |")
    for pol in ("supervisor", "one_active"):
        r = ref[pol]
        add(f"| {names[pol]} | {P[pol]['reachable_markings']} | {r['safe_states_given_up']} | {r['safe_edges_given_up']} | {'**yes**' if r['equals_maximally_permissive'] else 'no'} |")
    add("\n**Scaling with batch size (n A-parts + n B-parts):**\n")
    add("| Batch | Unrestricted markings (deadlocks) | One-active markings | Supervisor markings | Maximal reference | Supervisor = maximal? |")
    add("|---|---:|---:|---:|---:|:---:|")
    for r in sc:
        add(f"| {r['batch']} | {r['unrestricted_markings']} ({r['unrestricted_deadlocks']}) | {r['one_active_markings']} | "
            f"{r['supervisor_markings']} | {r['maximal_markings']} | {'yes' if r['supervisor_is_maximal'] else 'no'} |")

    add("\n## 3. Experiment 1 — deterministic timing grid (batch available at t = 0)\n")
    add(f"All 3⁴ = 81 combinations of processing times from {{2, 4, 8}} ticks, both dispatch priorities, {e1['runs_per_policy']} scenarios per policy.\n")
    a, o = e1["supervisor_vs_one_active"], e1["supervisor_vs_optimal"]
    add(f"- Unrestricted dispatch deadlocked in **{e1['unrestricted_deadlocked']} / {e1['runs_per_policy']}** scenarios "
        f"(greedy dispatch loads an A on M1 and a B on M2 at t = 0). One-active: {e1['one_active_deadlocked']} deadlocks. Supervisor: {e1['supervisor_deadlocked']} deadlocks.")
    add(f"- Supervisor vs one-active makespan: **{a['mean_reduction_pct']:.1f}% shorter on average** (range {a['min_reduction_pct']:.1f}%–{a['max_reduction_pct']:.1f}%); "
        f"strictly faster in {a['strictly_faster_in']} of {e1['runs_per_policy']} scenarios, never slower: {a['never_slower']}.")
    add(f"- The saving equals the closed form **min(a₁,a₂) + min(b₂,b₁) ticks** in every scenario: {a['closed_form_saving_matches_all']}. "
        "(Parts of one product pipeline through the machines; the supervisor makespan is max(2a₁+a₂, a₁+2a₂) + max(2b₂+b₁, b₂+2b₁); one-active is 2·(a₁+a₂+b₂+b₁).)")
    add(f"- Exact optimum over *all* dispatch policies (exhaustive timed search, deliberate idling allowed): the supervisor reaches it in "
        f"**{o['runs_at_optimum']} / {o['runs']}** scenarios (max gap {o['max_gap_pct']:.2f}%).")
    uo, us = e1["mean_utilisation"]["one_active"], e1["mean_utilisation"]["supervisor"]
    add(f"- Mean machine utilisation (processing time / makespan): one-active M1 {pct(uo['M1'])}, M2 {pct(uo['M2'])}; supervisor M1 {pct(us['M1'])}, M2 {pct(us['M2'])}.")
    add(f"- Mean waiting time before loading: one-active {e1['mean_queue_wait']['one_active']:.1f} ticks, supervisor {e1['mean_queue_wait']['supervisor']:.1f} ticks; "
        f"mean flow time: {e1['mean_flow_time']['one_active']:.1f} vs {e1['mean_flow_time']['supervisor']:.1f} ticks. "
        f"Total ticks the machines spend holding finished parts (blocking): {e1['mean_blocking_ticks']['supervisor']:.1f} ticks (supervisor).\n")

    add("## 4. Experiment 2 — Monte Carlo with staggered arrivals\n")
    add("Each part arrives at an integer time uniform in [0, spread]; 500 scenarios per cell; all three policies see identical scenarios "
        "(common random numbers). Deadlock rate: Wilson 95% interval. Saving: mean paired difference, bootstrap 95% interval.\n")
    add("| Time class | Spread | P(deadlock), unrestricted | Supervisor makespan | One-active makespan | Saving vs one-active (ticks) | Saving (%) |")
    add("|---|---:|---:|---:|---:|---:|---:|")
    for r in e2:
        if r["spread"] in (0, 8, 32, 128):
            add(f"| {r['time_class']} | {r['spread']} | {r['unrestricted_deadlock_rate']:.2f} [{r['deadlock_ci_lo']:.2f}, {r['deadlock_ci_hi']:.2f}] | "
                f"{r['supervisor_mean_makespan']:.1f} | {r['one_active_mean_makespan']:.1f} | "
                f"{r['saving_vs_one_active_mean']:.1f} [{r['saving_ci_lo']:.1f}, {r['saving_ci_hi']:.1f}] | {r['saving_pct']:.1f} |")
    tot_ctrl = sum(r["controlled_deadlocks"] for r in e2)
    nev = all(r["supervisor_never_slower_than_one_active"] for r in e2)
    add(f"\nControlled cells (both policies) had **{tot_ctrl} deadlocks** in {sum(r['n'] for r in e2) * 2} controlled runs; "
        f"the supervisor was never slower than one-active in any individual scenario: {nev}. Full table: `exp2_montecarlo.csv`.\n")
    add("*Caveat:* the arrival model is an assumption of this study, not a measurement of a real cell, so the deadlock *rates* are illustrative; "
        "the *existence* of the deadlock and its prevention are properties of the net and hold for every timing.\n")

    add("## 5. Python ↔ C++ cross-validation\n")
    add(f"- {cc['simulate_runs']} timed simulations (random processing times, arrival patterns, dispatch priorities, all three policies): "
        f"event logs compared byte for byte — **{cc['simulate_mismatches']} mismatches**.")
    add(f"- {cc['replay_traces']} event sequences ({cc['replay_steps']} steps) replayed through both implementations "
        f"(random walks, the shortest deadlock trace, and the timed logs); marking *and* enabled-transition set compared after every step — **{cc['replay_mismatches']} mismatches**.")
    add(f"- {cc['negative_tests']} illegal firings (e.g. `B_load` while the supervisor holds no permission token) rejected identically by both: **{cc['negative_failures']} failures**.")
    add("- The harness is not vacuous: `tests/test_crosscheck.py` feeds the C++ engine a different net and checks that a mismatch is reported.\n")

    add("## 6. Resource use of the C++ engine\n")
    env = bm["environment"]
    add(f"Measured on: {env['cpu']} ({env.get('machine', '?')}); {env['platform']}; {env['compiler']}; flags `{env['build_flags']}`; Python {env['python']}.\n")
    add("> **These numbers describe the machine they were measured on. Re-run `make reproduce` (or `python3 scripts/run_benchmark.py`) on the device you want to quote.**\n")
    add("| Case | Firings/run | C++ time per run | C++ per firing | C++ step latency p50 / p99 (ns) | Python time per run | Speed-up | C++ peak RSS | Model data | Python heap peak |")
    add("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for c in bm["cases"]:
        cp, py = c["cpp"], c["python"]
        add(f"| {c['label']} | {c['firings_per_run']} | {cp['mean_run_ns'] / 1e3:.2f} µs | {cp['mean_ns_per_firing']:.0f} ns | "
            f"{cp['step_ns_p50']} / {cp['step_ns_p99']} | {py['mean_run_ns'] / 1e3:.1f} µs | ×{c['speedup']:.0f} | "
            f"{cp['peak_rss_kb'] / 1024:.1f} MB | {cp['model_bytes'] / 1024:.1f} kB | {py['tracemalloc_peak_kb']:.0f} kB |")
    add("\nPeak RSS is dominated by the C++ runtime and shared libraries, not by the model. Step latency includes the cost of two clock reads. "
        "The maximum observed step latency is OS scheduling jitter on a non-real-time system and must not be quoted as a worst-case bound.\n")

    add("## 7. What this does and does not establish\n")
    add("- **Established (for the stated model):** the unrestricted cell can deadlock and the net shows exactly how; the control-place supervisor is deadlock-free, "
        "nonblocking, and exactly as permissive as any such supervisor can be (batches up to 4A + 4B); timed throughput gains over the conservative policy; "
        "two independent implementations agree on every event sequence tested.")
    add("- **Not established:** behaviour with machine failures, non-atomic transfers, intermediate buffers, more machines or routes, or batches beyond those enumerated; "
        "execution on a real PLC or embedded-Linux target (everything here is software with simulated machine signals); "
        "hard real-time behaviour. Control places for deadlock prevention are an established technique — the contribution here is the careful model, "
        "verification, evaluation and implementation, not a new algorithm.")
    (RESULTS / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote", RESULTS / "RESULTS.md")


if __name__ == "__main__":
    main()
